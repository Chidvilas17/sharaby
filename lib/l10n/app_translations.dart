  /// Translate [text] to Arabic if active locale is Arabic ('ar'), otherwise return English.
  static String tr(String text, [BuildContext? context]) {
    final isArabic = ThemeController.instance.isArabic;
    if (!isArabic) {
      // English mode: If text is bilingual like "Search / بحث" or "التاريخ / Date", extract English part
      if (text.contains(' / ')) {
        final parts = text.split(' / ');
        if (parts.length == 2) {
          if (parts[0].codeUnits.every((c) => c < 128)) {
            return parts[0].trim();
          } else if (parts[1].codeUnits.every((c) => c < 128)) {
            return parts[1].trim();
          }
        }
      }
      return text;
    }

    // Arabic mode
    final trimmed = text.trim();
    if (_ar.containsKey(trimmed)) {
      final translated = _ar[trimmed]!;
      final leading = text.substring(0, text.indexOf(trimmed));
      final trailing = text.substring(text.indexOf(trimmed) + trimmed.length);
      return '$leading$translated$trailing';
    }

    // Check if text is a bilingual pattern like "A / B"
    if (text.contains(' / ')) {
      final parts = text.split(' / ');
      if (parts.length == 2) {
        final p0IsArabic = parts[0].codeUnits.any((c) => c >= 0x0600 && c <= 0x06FF);
        final p1IsArabic = parts[1].codeUnits.any((c) => c >= 0x0600 && c <= 0x06FF);
        if (p0IsArabic && !p1IsArabic) {
          return parts[0].trim();
        } else if (p1IsArabic && !p0IsArabic) {
          return parts[1].trim();
        }
      }
    }

    // Dynamic pattern translations
    if (trimmed.startsWith('Failed to load') && trimmed.contains('nurses')) {
      return 'فشل تحميل بيانات التمريض';
    }
    if (trimmed.startsWith('Failed to load') && trimmed.contains('attendance')) {
      return 'فشل تحميل سجل الحضور';
    }
    if (trimmed.startsWith('Failed to load') && trimmed.contains('rates')) {
      return 'فشل تحميل الأسعار';
    }
    if (trimmed.startsWith('Failed to load') && trimmed.contains('accounts')) {
      return 'فشل تحميل الحسابات';
    }
    if (trimmed.startsWith('Failed to load') && trimmed.contains('doctors')) {
      return 'فشل تحميل بيانات الأطباء';
    }
    if (trimmed.startsWith('Failed to load') && trimmed.contains('patients')) {
      return 'فشل تحميل بيانات المرضى';
    }
    if (trimmed.startsWith('Failed to load') && trimmed.contains('expenses')) {
      return 'فشل تحميل المصروفات';
    }
    if (trimmed.startsWith('Failed to load') && trimmed.contains('salaries')) {
      return 'فشل تحميل الرواتب';
    }
    if (trimmed.startsWith('Failed to load')) {
      return 'فشل تحميل البيانات';
    }
    if (trimmed.startsWith('Failed to save') && trimmed.contains('Shift A')) {
      return 'فشل حفظ الوردية أ';
    }
    if (trimmed.startsWith('Failed to save') && trimmed.contains('Shift B')) {
      return 'فشل حفظ الوردية ب';
    }
    if (trimmed.startsWith('Failed to save') && trimmed.contains('Shift C')) {
      return 'فشل حفظ الوردية ج';
    }
    if (trimmed.startsWith('Failed to save')) {
      return 'فشل حفظ البيانات';
    }
    if (trimmed.startsWith('Failed to delete')) {
      return 'فشل الحذف';
    }
    if (trimmed.startsWith('Update failed')) {
      return 'فشل التحديث';
    }
    if (trimmed.startsWith('Are you sure you want to delete')) {
      return 'هل أنت متأكد من رغبتك في الحذف؟';
    }
    if (trimmed.startsWith('Total Expenses:')) {
      return trimmed.replaceFirst('Total Expenses:', 'إجمالي المصروفات:');
    }
    if (trimmed.startsWith('Total Income:')) {
      return trimmed.replaceFirst('Total Income:', 'إجمالي الإيرادات:');
    }
    if (trimmed.startsWith('Shift Salary:')) {
      return trimmed.replaceFirst('Shift Salary:', 'راتب الوردية:');
    }
    if (trimmed.endsWith('added successfully.')) {
      final name = trimmed.substring(0, trimmed.indexOf('added successfully.')).trim();
      return '$name تم الإضافة بنجاح.';
    }
    if (trimmed.endsWith('deleted successfully.')) {
      final name = trimmed.substring(0, trimmed.indexOf('deleted successfully.')).trim();
      return '$name تم الحذف بنجاح.';
    }
    if (trimmed.endsWith('updated successfully.')) {
      final name = trimmed.substring(0, trimmed.indexOf('updated successfully.')).trim();
      return '$name تم التحديث بنجاح.';
    }
    if (trimmed.endsWith('will be built next.')) {
      final name = trimmed.substring(0, trimmed.indexOf('will be built next.')).trim();
      return 'سيتم بناء $name لاحقاً.';
    }
    if (trimmed.startsWith('Accounts loaded for')) {
      return trimmed.replaceFirst('Accounts loaded for', 'تم تحميل الحسابات لـ');
    }

    return text;
  }

  static String text(String key, [BuildContext? context]) => tr(key, context);
