  /// Translate [text] to Arabic if active locale is Arabic ('ar'), otherwise return English.
  static String tr(String text, [BuildContext? context]) {
    final isArabic = ThemeController.instance.isArabic;
    if (!isArabic) {
      // English mode: If text is bilingual like "Search / بحث" or "التاريخ / Date", extract English part
      if (text.contains(' / ')) {
        final parts = text.split(' / ');
        if (parts.length == 2) {
          // Check which part is English (ASCII)
          if (parts[0].codeUnits.every((c) => c < 128)) {
            return parts[0].trim();
          } else if (parts[1].codeUnits.every((c) => c < 128)) {
            return parts[1].trim();
          }
        }
      }
      return text;
    }

    // Arabic mode
    final trimmed = text.trim();
    if (_ar.containsKey(trimmed)) {
      final translated = _ar[trimmed]!;
      // Preserve leading/trailing whitespace
      final leading = text.substring(0, text.indexOf(trimmed));
      final trailing = text.substring(text.indexOf(trimmed) + trimmed.length);
      return '$leading$translated$trailing';
    }

    // Check if text is a bilingual pattern like "A / B"
    if (text.contains(' / ')) {
      final parts = text.split(' / ');
      if (parts.length == 2) {
        // If one part is Arabic and other is English, return Arabic part
        final p0IsArabic = parts[0].codeUnits.any((c) => c >= 0x0600 && c <= 0x06FF);
        final p1IsArabic = parts[1].codeUnits.any((c) => c >= 0x0600 && c <= 0x06FF);
        if (p0IsArabic && !p1IsArabic) {
          return parts[0].trim();
        } else if (p1IsArabic && !p0IsArabic) {
          return parts[1].trim();
        }
      }
    }

    return text;
  }

  static String text(String key, [BuildContext? context]) => tr(key, context);
